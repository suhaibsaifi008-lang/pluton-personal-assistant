    def drag(self, start_x: int = 0, start_y: int = 0, end_x: int = 0, end_y: int = 0, source_target: str | None = None, destination_target: str | None = None, context: Any = None, **kwargs: Any) -> dict[str, Any]: ...
    def scroll(self, clicks: int = 0, x: int | None = None, y: int | None = None, context: Any = None) -> dict[str, Any]: ...


