@runtime_checkable
class IVisionDomain(Protocol):
    """Protocol for visual grounding, inspection, and verification."""

    def locate(self, target_description: str, confidence: float = 0.8, context: Any = None) -> dict[str, Any]: ...
    def inspect(self, prompt: str, image: Any = None, context: Any = None) -> dict[str, Any]: ...
