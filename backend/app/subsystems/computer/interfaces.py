    def create(self, path: str, is_dir: bool = False, context: Any = None) -> dict[str, Any]: ...
    def move(self, source: str, destination: str, context: Any = None) -> dict[str, Any]: ...
    def copy(self, source: str, destination: str, context: Any = None) -> dict[str, Any]: ...
    def rename(self, source: str, new_name: str, context: Any = None) -> dict[str, Any]: ...
    def delete(self, path: str, recursive: bool = False, context: Any = None) -> dict[str, Any]: ...
    def exists(self, path: str, context: Any = None) -> dict[str, Any]: ...


