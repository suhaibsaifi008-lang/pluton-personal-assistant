"""
PLUTON V2 — Canonical Computer Control Protocols & Interface Contracts
Defines runtime Protocols for all 12 computer control domains and low-level engines.
Every domain handler and concrete engine MUST implement its corresponding Protocol.
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


class CanonicalInterfaceError(RuntimeError):
    """Raised when a computer engine fails interface conformance verification."""
    pass


# -----------------------------------------------------------------------------
# 1. Window & UI Automation Protocols
# -----------------------------------------------------------------------------

@runtime_checkable
class IWindowDomain(Protocol):
    """Protocol for Window lifecycle and state manipulation."""

    def list_windows(self, visible_only: bool = True, context: Any = None) -> list[dict[str, Any]]: ...
    def find_window(self, target: str | int, context: Any = None) -> dict[str, Any] | None: ...
    def get_foreground_window(self, context: Any = None) -> dict[str, Any]: ...
    def focus_window(self, target: str | int, context: Any = None) -> dict[str, Any]: ...
    def close_window(self, target: str | int, context: Any = None) -> dict[str, Any]: ...
    def window_state(self, target: str | int | None = None, context: Any = None) -> dict[str, Any]: ...


@runtime_checkable
class IUIAEngine(Protocol):
    """Protocol for UI Automation Engine and low-level accessibility interactions."""

    def list_windows(self, visible_only: bool = True) -> list[dict[str, Any]]: ...
    def find_window(self, query: str) -> dict[str, Any] | None: ...
    def get_foreground_window(self) -> dict[str, Any]: ...
    def focus_window(self, hwnd: int) -> bool: ...
    def close_window(self, hwnd: int) -> bool: ...
    def window_state(self, hwnd: int) -> dict[str, Any]: ...
    def inspect_tree(self, hwnd: int | None = None, max_depth: int = 4) -> dict[str, Any]: ...
    def find_element(self, query: str, hwnd: int | None = None, control_type: str | None = None) -> dict[str, Any] | None: ...
    def find_elements(self, query: str, hwnd: int | None = None, control_type: str | None = None) -> list[dict[str, Any]]: ...
    def invoke(self, element_id: str | int, hwnd: int | None = None) -> dict[str, Any]: ...
    def set_value(self, element_id: str | int, value: str, hwnd: int | None = None) -> dict[str, Any]: ...
    def toggle(self, element_id: str | int, hwnd: int | None = None) -> dict[str, Any]: ...
    def select(self, element_id: str | int, value: str | None = None, hwnd: int | None = None) -> dict[str, Any]: ...
    def expand_collapse(self, element_id: str | int, expand: bool = True, hwnd: int | None = None) -> dict[str, Any]: ...
    def focus(self, element_id: str | int, hwnd: int | None = None) -> dict[str, Any]: ...


@runtime_checkable
class IUIDomain(Protocol):
    """Protocol for semantic UI element domain handler."""

    def inspect_tree(self, hwnd: int = 0, depth: int = 4, context: Any = None) -> list[dict[str, Any]] | dict[str, Any]: ...
    def find_element(self, query: str, hwnd: int = 0, control_type: str | None = None, context: Any = None) -> dict[str, Any] | None: ...
    def find_elements(self, query: str, hwnd: int = 0, control_type: str | None = None, context: Any = None) -> list[dict[str, Any]]: ...
    def invoke(self, target: str, hwnd: int = 0, context: Any = None) -> dict[str, Any]: ...
    def set_value(self, target: str, value: str, hwnd: int = 0, context: Any = None) -> dict[str, Any]: ...
    def toggle(self, target: str, hwnd: int = 0, context: Any = None) -> dict[str, Any]: ...
    def select(self, target: str, hwnd: int = 0, context: Any = None) -> dict[str, Any]: ...
    def expand_collapse(self, target: str, expand: bool = True, hwnd: int = 0, context: Any = None) -> dict[str, Any]: ...
    def focus(self, target: str, hwnd: int = 0, context: Any = None) -> dict[str, Any]: ...


IUIADomain = IUIDomain


